-- P5 - Table partitioning: seatings -> RANGE partitions on slot_id, one partition per semester.
-- Why slot_id: the P1 rules (UNIQUE seat+slot, UNIQUE student+slot) include slot_id, and PostgreSQL
-- only allows a UNIQUE index on a partitioned table if it contains the partition key.
-- Safe to re-run: if seatings is already partitioned nothing happens.
\set ON_ERROR_STOP on
SELECT (relkind = 'p') AS already_partitioned FROM pg_class
WHERE relname = 'seatings' AND relnamespace = 'public'::regnamespace \gset
\if :already_partitioned
  \echo 'seatings is already partitioned - skipping the migration'
\else
  SELECT MIN(slot_id) AS lo, MAX(slot_id) AS hi FROM exam_slots WHERE semester = '2025/2026-S1' \gset
  \echo '=== BEFORE (single table): one semester, slot_id' :lo '..' :hi '==='
  EXPLAIN (ANALYZE, COSTS OFF) SELECT status, COUNT(*) FROM seatings WHERE slot_id BETWEEN :lo AND :hi GROUP BY status;

  CREATE TABLE seatings_part (
      seating_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
      student_id   INTEGER NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
      seat_id      INTEGER NOT NULL REFERENCES seats(seat_id),
      paper_id     INTEGER NOT NULL,
      slot_id      INTEGER NOT NULL,
      status       VARCHAR(10) NOT NULL DEFAULT 'ASSIGNED' CHECK (status IN ('ASSIGNED','SAT','ABSENT','CANCELLED')),
      assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
      cancelled_at TIMESTAMPTZ,
      PRIMARY KEY (seating_id, slot_id),
      FOREIGN KEY (paper_id, slot_id) REFERENCES exam_papers(paper_id, slot_id),
      CONSTRAINT chk_cancel_invariant CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
  ) PARTITION BY RANGE (slot_id);

  CREATE UNIQUE INDEX uniq_active_seat_per_slot_p    ON seatings_part (seat_id, slot_id)    WHERE status IN ('ASSIGNED','SAT');
  CREATE UNIQUE INDEX uniq_active_student_per_slot_p ON seatings_part (student_id, slot_id) WHERE status IN ('ASSIGNED','SAT');

  DO $$
  DECLARE r record;
  BEGIN
      FOR r IN SELECT semester, MIN(slot_id) AS lo, MAX(slot_id) AS hi FROM exam_slots GROUP BY semester ORDER BY 2 LOOP
          EXECUTE format('CREATE TABLE seatings_%s PARTITION OF seatings_part FOR VALUES FROM (%s) TO (%s)',
                         lower(replace(replace(r.semester, '/', '_'), '-', '_')), r.lo, r.hi + 1);
      END LOOP;
      -- the next semester(s): slot ids after the last existing slot
      EXECUTE format('CREATE TABLE seatings_next PARTITION OF seatings_part FOR VALUES FROM (%s) TO (%s)',
                     (SELECT MAX(slot_id) + 1 FROM exam_slots), (SELECT MAX(slot_id) + 1001 FROM exam_slots));
  END $$;
  CREATE TABLE seatings_default PARTITION OF seatings_part DEFAULT;   -- must stay empty

  INSERT INTO seatings_part (seating_id, student_id, seat_id, paper_id, slot_id, status, assigned_at, cancelled_at)
  SELECT seating_id, student_id, seat_id, paper_id, slot_id, status, assigned_at, cancelled_at FROM seatings;
  SELECT setval(pg_get_serial_sequence('seatings_part', 'seating_id'), (SELECT MAX(seating_id) FROM seatings_part));

  SELECT (SELECT COUNT(*) FROM seatings) AS old_rows, (SELECT COUNT(*) FROM seatings_part) AS new_rows,
         (SELECT COUNT(*) FROM seatings_default) AS rows_in_default_partition \gset
  \echo 'old rows' :old_rows ' new rows' :new_rows ' rows in DEFAULT partition' :rows_in_default_partition '(must be 0)'
  SELECT :old_rows = :new_rows AND :rows_in_default_partition = 0 AS migration_ok \gset
  \if :migration_ok
    BEGIN;
    DROP TABLE seatings CASCADE;
    ALTER TABLE seatings_part RENAME TO seatings;
    ALTER TABLE seatings RENAME CONSTRAINT seatings_part_pkey TO seatings_pkey;
    ALTER INDEX uniq_active_seat_per_slot_p    RENAME TO uniq_active_seat_per_slot;
    ALTER INDEX uniq_active_student_per_slot_p RENAME TO uniq_active_student_per_slot;
    -- re-create the P1 triggers on the new table (the functions still exist)
    CREATE TRIGGER trg_seating_rules BEFORE INSERT OR UPDATE OF student_id, seat_id, paper_id, status ON seatings
        FOR EACH ROW EXECUTE FUNCTION trg_fn_seating_rules();
    CREATE TRIGGER trg_one_seat_per_slot BEFORE INSERT OR UPDATE OF student_id, seat_id, slot_id, status ON seatings
        FOR EACH ROW EXECUTE FUNCTION trg_fn_one_seat_per_slot();
    COMMIT;
    ANALYZE seatings;
  \else
    \echo 'MIGRATION CHECK FAILED - old table kept'
    \quit
  \endif
\endif

\echo '=== Rows per partition ==='
SELECT c.relname AS partition, pg_get_expr(c.relpartbound, c.oid) AS bounds, (xpath('/row/n/text()', query_to_xml('SELECT COUNT(*) AS n FROM ' || quote_ident(c.relname), false, true, '')))[1]::text::int AS row_count
FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
WHERE i.inhparent = 'seatings'::regclass ORDER BY c.relname;

SELECT MIN(slot_id) AS lo, MAX(slot_id) AS hi FROM exam_slots WHERE semester = '2025/2026-S1' \gset
\echo '=== AFTER (partitioned): same one-semester query - only one partition is read ==='
EXPLAIN (ANALYZE, COSTS OFF) SELECT status, COUNT(*) FROM seatings WHERE slot_id BETWEEN :lo AND :hi GROUP BY status;

\echo '=== P1 rules still enforced on the partitioned table (triggers) ==='
SELECT tgname AS trigger_name FROM pg_trigger WHERE tgrelid = 'seatings'::regclass AND NOT tgisinternal ORDER BY 1;
SELECT indexname FROM pg_indexes WHERE tablename = 'seatings' AND indexname LIKE 'uniq_active%' ORDER BY 1;

\echo '=== Maintenance demo: detach and re-attach the oldest semester (archiving without DELETE) ==='
SELECT COUNT(*) AS rows_before_detach FROM seatings;
ALTER TABLE seatings DETACH PARTITION seatings_2022_2023_s1;
SELECT COUNT(*) AS rows_after_detach FROM seatings;
SELECT COUNT(*) AS rows_in_detached_table FROM seatings_2022_2023_s1;
SELECT MIN(slot_id) AS dlo, MAX(slot_id) + 1 AS dhi FROM seatings_2022_2023_s1 \gset
ALTER TABLE seatings ATTACH PARTITION seatings_2022_2023_s1 FOR VALUES FROM (:dlo) TO (:dhi);
SELECT COUNT(*) AS rows_after_reattach FROM seatings;
